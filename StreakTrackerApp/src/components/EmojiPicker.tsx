const NUM_COLUMNS = 6;
const SCREEN_WIDTH = Dimensions.get("window").width;
const PICKER_WIDTH = SCREEN_WIDTH * 0.9;
const EMOJI_CELL_SIZE = Math.floor((PICKER_WIDTH - 16) / NUM_COLUMNS);

type Props = {
  visible: boolean;
  onSelect: (emoji: string) => void;
  onClose: () => void;
};

export default function EmojiOverlayPicker({
  visible,
  onSelect,
  onClose,
}: Props) {
  const [activeCategory, setActiveCategory] =
    useState<keyof typeof emojiCategories>("😀");
  const theme = useTheme();
  const styles = getStyles(theme);

  const renderEmoji = ({ item }: { item: string }) => (
    <TouchableOpacity
      style={styles.emojiCell}
      onPress={() => {
        onSelect(item);
        onClose();
      }}
    >
      <Text style={styles.emoji}>{item}</Text>
    </TouchableOpacity>
  );

  return (
    <Modal visible={visible} transparent animationType="fade">
      <TouchableOpacity
        style={styles.backdrop}
        activeOpacity={1}
        onPress={onClose}
      >
        <View style={styles.pickerContainer}>
          {/* Tabs */}
          <ScrollView
            horizontal
            showsHorizontalScrollIndicator={false}
            style={styles.tabs}
          >
            {Object.keys(emojiCategories).map((cat) => (
              <TouchableOpacity
                key={cat}
                onPress={() =>
                  setActiveCategory(cat as keyof typeof emojiCategories)
                }
                style={[styles.tab, cat === activeCategory && styles.activeTab]}
              >
                <Text style={styles.tabText}>{cat}</Text>
              </TouchableOpacity>
            ))}
          </ScrollView>

          {/* Grid */}
          <FlatList
            data={emojiCategories[activeCategory]}
            renderItem={renderEmoji}
            keyExtractor={(item, index) => item + index}
            numColumns={NUM_COLUMNS}
            scrollEnabled
            contentContainerStyle={{ paddingBottom: 8 }}
          />
        </View>
      </TouchableOpacity>
    </Modal>
  );
}

const getStyles = (colors: typeof Colors.light) =>
  StyleSheet.create({
    backdrop: {
      flex: 1,
      backgroundColor: "#00000099",
      justifyContent: "center",
      alignItems: "center",
    },
    pickerContainer: {
      backgroundColor: colors.background200,
      width: "90%",
      maxHeight: 400,
      borderRadius: 12,
      padding: 8,
    },
    tabs: {
      flexDirection: "row",
      borderBottomWidth: 2,
      borderColor: "transparent",
      marginBottom: 5,
    },
    tab: {
      paddingHorizontal: 12,
      paddingVertical: 6,
      borderRadius: 8,
      marginBottom: 4,
    },
    activeTab: {
      backgroundColor: colors.primary500 + "22",
    },
    tabText: {
      fontSize: 22,
      color: colors.text900,
      fontFamily: "Roboto",
    },
    emojiCell: {
      width: EMOJI_CELL_SIZE,
      height: EMOJI_CELL_SIZE,
      justifyContent: "center",
      alignItems: "center",
    },
    emoji: {
      fontSize: 28,
    },
  });
